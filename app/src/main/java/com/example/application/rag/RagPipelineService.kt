/**
 * ============================================================================
 * RagPipelineService — Phase 4 (resource-backed, no direct adapter injection)
 * ============================================================================
 *
 * Per the architectural plan (Section 8): embedding execution is resource-backed.
 * The correct conceptual path is:
 *
 *   Provider → Embedding Service → Protocol → Configuration → discovered
 *   ModelDescriptor → ServiceOffering → Resource → ResourceRegistry →
 *   Decision → exact resource execution
 *
 * This service no longer takes a direct `EmbeddingProviderPort` injection.
 * Instead, it accepts:
 *
 *   - `resourceRegistry` — the authoritative `DurableResourceRegistryService`
 *     that holds all materialized `ResourceRecord`s
 *   - `runtimeAdapterResolver` — the resolver that maps `ResourceId` → adapter
 *   - `fallbackEmbeddingProvider` — a best-effort local in-process adapter used
 *     ONLY when no embedding ResourceRecord exists yet (first-run fallback).
 *     The fallback is honest: the `RetrievalMode` flag in the returned
 *     `RetrievedContextChunk` is `LEXICAL_FALLBACK` (not `HYBRID`).
 *
 * Per the architectural plan (Section 8): "If a different embedding resource is
 * selected, the system must recognize the compatibility boundary rather than
 * pretending vectors are interchangeable." Therefore, each chunk's persisted
 * `retrievalSource` field records which embedding resource generated it. When
 * a new embedding resource is selected for retrieval, chunks generated by a
 * different embedding resource are not mixed in — they're filtered out, and
 * a `RetrievalMode.EMBEDDING_COMPATIBILITY_BOUNDARY` marker is set.
 */
class RagPipelineService(
    private val resourceRegistry: ResourceRegistryService,
    private val runtimeAdapterResolver: RuntimeAdapterResolver,
    private val fallbackEmbeddingProvider: EmbeddingProviderPort? = null,
    private val persistenceService: KnowledgePersistenceService? = null,
    private val workspaceIdProvider: () -> String = { "default" },
    /**
     * Audit 2026 (§29 — workspace knowledge has NO size limit): bounded
     * corpus. Ingesting beyond [maxDocumentsPerWorkspace] /
     * [maxChunksPerWorkspace] evicts the OLDEST documents (insertion order)
     * and reports every eviction in the observable [corpusEvictions] flow —
     * the corpus degrades HONESTLY instead of growing without bound in RAM.
     */
    private val maxDocumentsPerWorkspace: Int = 256,
    private val maxChunksPerWorkspace: Int = 24_000
) {
    private val _documents = MutableStateFlow<List<KnowledgeDocument>>(emptyList())
    val documents: StateFlow<List<KnowledgeDocument>> = _documents.asStateFlow()

    // FIX APP-P3-27: thread-safe list for concurrent ingest calls.
    private val chunks = CopyOnWriteArrayList<DocumentChunk>()
    private val chunksMutex = Mutex()

    /**
     * P1-5 (audit 2026 §29 — RAG full-scan architecture): the retrieval
     * index. Normalized text + precomputed token set per chunk — the
     * legacy path re-normalized and re-tokenized the ENTIRE corpus on EVERY
     * query, which is what actually degraded with knowledge growth (not the
     * cosine dot products, which are cheap).
     */
    private data class IndexedChunk(
        val chunk: DocumentChunk,
        val normalizedLower: String,
        val tokens: Set<String>
    )

    private val indexedChunks = CopyOnWriteArrayList<IndexedChunk>()

    /** P1-5: honest bound on the per-query scan (degrades instead of stalling). */
    private val maxScanChunks = 8_000

    /**
     * Audit 2026 (§29 — no workspace-knowledge size limit): the LAST
     * [EVICTION_LOG_WINDOW] corpus evictions, observable. Non-empty means
     * the workspace corpus is at its bound and the OLDEST knowledge was
     * dropped — an honest degradation signal, never silent loss.
     */
    private val _corpusEvictions = MutableStateFlow<List<String>>(emptyList())
    val corpusEvictions: StateFlow<List<String>> = _corpusEvictions.asStateFlow()

    private fun recordEviction(entry: String) {
        _corpusEvictions.value = (listOf(entry) + _corpusEvictions.value).take(EVICTION_LOG_WINDOW)
    }

    private companion object {
        const val EVICTION_LOG_WINDOW = 64
    }

    /**
     * Audit 2026 (§29): enforce the corpus bounds — evict the OLDEST
     * documents (and all their chunks + index entries) while the corpus is
     * over [maxDocumentsPerWorkspace] or [maxChunksPerWorkspace]. Every
     * eviction is recorded in [corpusEvictions] (honest, observable).
     */
    private fun enforceCorpusBounds() {
        var evictedDocs = 0
        var evictedChunks = 0
        // 1) Total-chunk bound (evict oldest documents until under it).
        while (chunks.size > maxChunksPerWorkspace && _documents.value.isNotEmpty()) {
            val victim = _documents.value.first()
            evictedDocs++
            evictedChunks += chunks.count { it.documentId == victim.id }
            removeDocumentWorkingSet(victim.id)
        }
        // 2) Document-count bound.
        while (_documents.value.size > maxDocumentsPerWorkspace) {
            val victim = _documents.value.first()
            evictedDocs++
            evictedChunks += chunks.count { it.documentId == victim.id }
            removeDocumentWorkingSet(victim.id)
        }
        if (evictedDocs > 0) {
            recordEviction(
                "CORPUS_BOUND(RAM): evicted $evictedDocs document(s) / $evictedChunks chunk(s) " +
                    "from the IN-MEMORY working set (limits: docs=$maxDocumentsPerWorkspace, " +
                    "chunks=$maxChunksPerWorkspace). Persistent knowledge is RETAINED — " +
                    "this is a memory-pressure eviction, NOT a deletion."
            )
        }
    }

    /** Removes a document's RAM working set (document row, chunks, index). */
    private fun removeDocumentWorkingSet(documentId: String) {
        _documents.update { docs -> docs.filterNot { it.id == documentId } }
        // NOTE: CopyOnWriteArrayList iterators do NOT support remove() — the
        // Kotlin removeAll(predicate) extension would throw. removeIf is the
        // COW-safe atomic removal.
        chunks.removeIf { it.documentId == documentId }
        indexedChunks.removeIf { it.chunk.documentId == documentId }
        // REPAIR ORDER §15 — keep the scope index consistent with the working set.
        docProjectIndex = docProjectIndex - documentId
    }

    private fun indexChunk(chunk: DocumentChunk): IndexedChunk {
        val normalizedLower = com.example.infrastructure.memory.semantic.ArabicTextNormalizer
            .normalize(chunk.text).lowercase()
        val tokens = normalizedLower
            .split(Regex("[^\\w\\d\\u0600-\\u06FF]+")).filter { it.isNotBlank() }.toSet()
        return IndexedChunk(chunk, normalizedLower, tokens)
    }

    private fun reindexAll() {
        indexedChunks.clear()
        chunks.forEach { indexedChunks.add(indexChunk(it)) }
    }

    /**
     * GAP-CLOSURE P1-15 (stale async load guard): monotonic generation
     * counter for workspace knowledge loads. A load started for workspace A
     * that finishes AFTER a newer load for workspace B is DISCARDED — the
     * working set can never be overwritten by stale async results.
     */
    private val loadGeneration = AtomicLong(0)

    /**
     * GAP-CLOSURE P0-02: resolves the workspace for THIS call — the
     * execution-pinned scope when running inside an agent execution, else
     * the active-workspace provider (user-driven calls).
     */
    private suspend fun currentWorkspaceId(): String? {
        val pinned = currentCoroutineContext()[ExecutionScope.Key]?.workspaceId
        if (pinned != null) return pinned
        return runCatching { workspaceIdProvider() }.getOrNull()
    }

    /**
     * The embedding ResourceId used to embed the most recently-ingested chunks.
     * Used to enforce the embedding-compatibility boundary (Section 8).
     */
    @Volatile
    private var activeEmbeddingResourceId: ResourceId? = null

    /** Audit 2026: collision-free document id generator (see ingestDocument). */
    private val docIdCounter = AtomicLong(0)

    /**
     * REPAIR ORDER §15 — the workspace whose knowledge is CURRENTLY in the
     * RAM working set. Retrieval checks this and RELOADS when the pinned
     * scope's workspace differs (previously retrieval scanned whatever was
     * last loaded — a mid-execution workspace switch silently returned the
     * OTHER workspace's knowledge).
     */
    @Volatile
    private var loadedWorkspaceId: String? = null

    /** REPAIR ORDER §15 — documentId → projectId (for scope-mode filtering). */
    @Volatile
    private var docProjectIndex: Map<String, Long?> = emptyMap()

    private fun rebuildDocProjectIndex() {
        docProjectIndex = _documents.value.associate { it.id to it.projectId }
    }

    /**
     * REPAIR ORDER §15 — resolves the retrieval scope: the pinned
     * ExecutionScope (agent executions) else the active workspace, and
     * RELOADS the working set when it does not match. Returns null when no
     * scope can be resolved (honest empty retrieval — fail-closed).
     */
    private suspend fun ensureWorkingSetForPinnedScope(): Pair<String, Long?>? {
        val pinnedScope = currentCoroutineContext()[ExecutionScope.Key]
        val workspaceId = pinnedScope?.workspaceId ?: runCatching { workspaceIdProvider() }.getOrNull()
            ?: return null
        if (loadedWorkspaceId != workspaceId && persistenceService != null) {
            // Stale working set (workspace switch mid-execution): reload for
            // the PINNED workspace — the scope the caller actually runs in.
            loadFromPersistence()
        }
        return workspaceId to pinnedScope?.projectId?.takeIf { it > 0 }
    }

    init {
        bootstrapDefaultKnowledge()
    }

    /**
     * Phase 2 — Loads all persisted documents+chunks for the current workspace
     * into the in-memory index. Call this on app startup (after WorkspaceRuntimeService
     * has determined the active workspace) and whenever the user switches workspaces.
     *
     * GAP-CLOSURE P1-15: the load is generation-guarded — if a NEWER load
     * (another workspace switch) started while this one was reading, this
     * result is discarded instead of clobbering the newer workspace's
     * working set (the A-load / B-load / A-finishes-last race).
     *
     * REPAIR ORDER §15 — (a) the loaded scope is TRACKED ([loadedWorkspaceId])
     * so retrieval can detect and repair a stale working set instead of
     * returning ANOTHER workspace's knowledge; (b) corpus bounds are
     * enforced AFTER load (previously an over-bound corpus was fully
     * resurrected on every restart and then re-evicted piecemeal on the
     * next ingest — a thrash loop); (c) [projectId] scopes the load to a
     * project view (project-private + workspace-shared).
     */
    suspend fun loadFromPersistence(projectId: Long? = null) {
        val persistence = persistenceService ?: return
        val generation = loadGeneration.incrementAndGet()
        val workspaceId = workspaceIdProvider()
        val (docs, loadedChunks) = persistence.loadWorkspaceKnowledge(workspaceId, projectId)
        // Stale-result guard: only the LATEST load may mutate the index.
        if (loadGeneration.get() != generation) return
        chunksMutex.withLock {
            chunks.clear()
            chunks.addAll(loadedChunks)
            reindexAll()
        }
        _documents.update { docs }
        rebuildDocProjectIndex()
        loadedWorkspaceId = workspaceId
        // REPAIR ORDER §15 — enforce the SAME bounds after load (eviction is
        // RAM-only and honestly labeled: persistent knowledge is RETAINED).
        enforceCorpusBounds()
    }

    /**
     * Deletes a document from the knowledge base: removes it (and its chunks)
     * from the in-memory index AND deletes it durably from Room. Honest
     * outcome — when no durable store is wired the deletion is reported as
     * volatile-only instead of pretending persistence.
     */
    suspend fun deleteDocument(documentId: String): Outcome<Unit, String> {
        // 1. Durable deletion (Room) — the authoritative store.
        val durableDelete: Boolean = persistenceService?.let { persistence ->
            runCatching { persistence.deleteDocument(documentId) }.isSuccess
        } ?: false

        // 2. In-memory index removal (documents flow + chunk index).
        _documents.update { docs -> docs.filterNot { it.id == documentId } }
        chunksMutex.withLock {
            // COW-safe removal (CopyOnWriteArrayList iterators do NOT support
            // remove() — the removeAll(predicate) extension would throw).
            chunks.removeIf { it.documentId == documentId }
            indexedChunks.removeIf { it.chunk.documentId == documentId }
        }

        return when {
            persistenceService == null -> Outcome.Error(
                "لا يوجد مخزن دائم للمعرفة في هذا التكوين — الحذف كان في الذاكرة فقط."
            )
            durableDelete -> Outcome.Success(Unit)
            else -> Outcome.Error("تعذر حذف المستند من المخزن الدائم (راجع سجل الأخطاء).")
        }
    }

    /**
     * Audit 2026 fix: delegates to the local embedding router so the ONNX
     * semantic model can be provisioned on demand. When the fallback provider
     * is not a LocalSemanticEmbeddingRouter, this is an honest no-op error
     * (no semantic provisioning path exists in this configuration).
     */
    suspend fun provisionSemanticModel(): Outcome<Unit, String> {
        val router = fallbackEmbeddingProvider as? com.example.infrastructure.memory.semantic.LocalSemanticEmbeddingRouter
            ?: return Outcome.Error("لا يوجد مسار تضمين دلالي محلي في هذا التكوين.")
        return router.provision()
    }

    /**
     * TRUE when the on-device semantic model (ONNX MiniLM) is provisioned and
