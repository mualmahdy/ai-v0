    suspend fun retrieveRelevantContext(query: String, topK: Int = 4): AssembledRagContext =
        retrieveRelevantContextInternal(query, topK, RetrievalScopeMode.PROJECT_AND_WORKSPACE)

    /**
     * REPAIR ORDER §15 — EXPLICIT retrieval scope mode. The default remains
     * PROJECT_AND_WORKSPACE (backward compatible); callers may tighten to
     * PROJECT_ONLY / WORKSPACE_ONLY / APPLICATION. Cross-project private
     * knowledge is NEVER retrievable regardless of mode (sibling isolation).
     */
    suspend fun retrieveRelevantContext(
        query: String,
        topK: Int = 4,
        scopeMode: RetrievalScopeMode
    ): AssembledRagContext =
        retrieveRelevantContextInternal(query, topK, scopeMode)

    private suspend fun retrieveRelevantContextInternal(
        query: String,
        topK: Int,
        scopeMode: RetrievalScopeMode = RetrievalScopeMode.PROJECT_AND_WORKSPACE
    ): AssembledRagContext = withContext(Dispatchers.Default) {
        val (embeddingProvider, usedResourceId) = resolveEmbeddingProvider()

        // --------------------------------------------------------------
        // REPAIR ORDER §15 — SCOPED RETRIEVAL: resolve the caller's pinned
        // (or active) workspace/project, repair a stale working set, and
        // filter the candidate chunks by the requested SCOPE MODE. This is
        // the structural fix for "retrieval was a GLOBAL working-set scan":
        // another workspace's — or a sibling project's private — knowledge
        // can no longer be silently retrieved.
        // --------------------------------------------------------------
        val retrievalScope = ensureWorkingSetForPinnedScope()
        val pinnedProjectId = retrievalScope?.second
        val scopeFilter: (String) -> Boolean = { documentId ->
            val docProject = docProjectIndex[documentId]
            when (scopeMode) {
                RetrievalScopeMode.PROJECT_ONLY ->
                    pinnedProjectId != null && docProject == pinnedProjectId
                // No pinned project = the caller runs at WORKSPACE scope:
                // the whole (workspace-bounded) working set is visible.
                // With a pinned project: own private + workspace-shared.
                RetrievalScopeMode.PROJECT_AND_WORKSPACE ->
                    pinnedProjectId == null || docProject == null || docProject == pinnedProjectId
                RetrievalScopeMode.WORKSPACE_ONLY -> docProject == null
                RetrievalScopeMode.APPLICATION -> false // no app-shared knowledge persisted yet — honest empty
            }
        }

        val providerIsSemantic = isProviderSemantic(embeddingProvider)

        val queryVector = if (embeddingProvider != null) {
            val outcome = embeddingProvider.generateEmbeddings(listOf(query))
            if (outcome is Outcome.Success) (outcome.value.firstOrNull() ?: generateLexicalVector(query))
            else generateLexicalVector(query)
        } else {
            generateLexicalVector(query)
        }

        val retrievalMode = when {
            embeddingProvider == null -> RetrievalMode.LEXICAL_FALLBACK
            providerIsSemantic -> RetrievalMode.HYBRID
            else -> RetrievalMode.LEXICAL_FALLBACK // hash fallback — honestly labeled
        }

        val normalizedQuery = com.example.infrastructure.memory.semantic.ArabicTextNormalizer.normalize(query)
        val queryTokens = normalizedQuery.lowercase()
            .split(Regex("[^\\w\\d\\u0600-\\u06FF]+")).filter { it.isNotBlank() }.toSet()

        // ------------------------------------------------------------------
        // P1-5 (audit 2026 §29 — retrieval was a FULL re-tokenized scan +
        // two full sorts): the scan now uses the PRECOMPUTED per-chunk index
        // (normalized text + token set — computed once at ingest/load, not
        // per query), a LEXICAL PRE-FILTER (only chunks sharing at least one
        // query token are lexically scored — irrelevant chunks skip token
        // arithmetic entirely), a BOUNDED scan (maxScanChunks; a larger
        // corpus degrades HONESTLY via isTruncated instead of stalling) and
        // a single bounded top-K selection instead of two O(N log N) sorts.
        // ------------------------------------------------------------------
        val candidates = indexedChunks
        val scanBound = minOf(candidates.size, maxScanChunks)
        val scanWasTruncated = candidates.size > maxScanChunks

        // Bounded top-(topK*2) selection via a min-heap of relevance.
        val bound = (topK * 2).coerceAtLeast(2)
        val heap = java.util.PriorityQueue<RetrievedContextChunk>(
            compareBy<RetrievedContextChunk> { it.relevanceScore }
        )

        for (i in 0 until scanBound) {
            val indexed = candidates[i]
            val chunk = indexed.chunk
            // REPAIR ORDER §15 — scope-mode membership check BEFORE any
            // scoring work: out-of-scope chunks (sibling project private,
            // other-workspace) are skipped entirely.
            if (!scopeFilter(chunk.documentId)) continue
            val chunkEmbeddingId = chunk.metadata["embeddingResourceId"]
            // Compatibility boundary: chunks embedded by a DIFFERENT embedding
            // resource than the active one cannot be compared semantically.
            // GAP-07 (Design Closure 2026, ADR-4): the boundary is ALSO
            // dimension-space honest — the local-128 resource can UPGRADE
            // from lexical to ONNX semantic vectors under the SAME resource
            // id (the router seam). A lexical-embedded chunk (metadata
            // embeddingSemantic=false) must never be semantically scored
            // against a semantic query vector (different vector spaces), and
            // vice versa — such chunks stay lexical-scored only, honestly.
            val chunkWasSemantic = chunk.metadata["embeddingSemantic"]?.toBoolean() ?: false
            val vectorCompatible = (chunkEmbeddingId == null ||
                usedResourceId == null ||
                chunkEmbeddingId == usedResourceId.value ||
                chunkEmbeddingId == "local_lexical") &&
                chunkWasSemantic == providerIsSemantic

            val sim = if (vectorCompatible) {
                val chunkVector = chunk.vector ?: generateLexicalVector(chunk.text)
                computeCosineSimilarity(queryVector.values, chunkVector.values)
            } else 0.0f

            // P1-5 LEXICAL PRE-FILTER: with precomputed token sets, a chunk
            // sharing NO query token cannot have a positive lexical F1 — skip
            // the scoring work for it entirely.
            val overlap = if (queryTokens.isEmpty() || indexed.tokens.isEmpty()) 0.0f
            else if (queryTokens.none { it in indexed.tokens }) 0.0f
            else {
                val common = queryTokens.intersect(indexed.tokens).size.toFloat()
                val precision = common / indexed.tokens.size
                val recall = common / queryTokens.size
                if (precision + recall > 0f) 2f * precision * recall / (precision + recall) else 0f
            }

            val semanticWeight = if (vectorCompatible && providerIsSemantic) 0.6f else 0.0f
            val lexicalWeight = 1.0f - semanticWeight
            val combinedScore = (sim * semanticWeight + overlap * lexicalWeight).coerceIn(0.0f, 1.0f)
            if (combinedScore <= 0.05f) continue

            val scored = RetrievedContextChunk(
                chunk = chunk,
                relevanceScore = combinedScore,
                retrievalMode = retrievalMode,
                snippet = chunk.text
            )
            if (heap.size < bound) {
                heap.add(scored)
            } else if (heap.peek().relevanceScore < combinedScore) {
                heap.poll()
                heap.add(scored)
            }
        }

        val scoredChunks = heap.toList()
            .asSequence()
            // Lexical rerank pass: boost candidates whose text actually
            // contains the (normalized) query tokens verbatim.
            .map { scored ->
                val containsBoost = if (scored.chunk.text.contains(query, ignoreCase = true) ||
                    com.example.infrastructure.memory.semantic.ArabicTextNormalizer
                        .normalize(scored.chunk.text).contains(normalizedQuery, ignoreCase = true)
                ) 0.1f else 0.0f
                scored.copy(relevanceScore = (scored.relevanceScore + containsBoost).coerceAtMost(1.0f))
            }
            .sortedByDescending { it.relevanceScore }
            .take(topK)
            .toList()

        val assembledText = buildString {
            appendLine("=== سياق المعرفة المسترجع (RAG Knowledge Base) ===")
            scoredChunks.forEachIndexed { i, c ->
                appendLine("[مصدر ${i + 1}: ${c.chunk.documentTitle} (صلة: ${"%.2f".format(c.relevanceScore)})]")
                appendLine(c.chunk.text)
                appendLine()
            }
        }

        AssembledRagContext(
            query = query,
            formattedContextText = assembledText,
            retrievedChunks = scoredChunks,
            totalTokensEstimated = assembledText.length / 4,
            // P1-5: honest truncation flag when the corpus exceeded the
            // bounded scan (never a silent partial scan).
            isTruncated = scanWasTruncated
        )
    }

    /**
     * TRUE only when the embedding provider actually produces semantic
     * vectors (a trained model — e.g. ONNX MiniLM or a cloud embedding API).
     * The deterministic hash fallback is NOT semantic and is labeled as such.
     */
    private fun isProviderSemantic(provider: EmbeddingProviderPort?): Boolean {
        if (provider == null) return false
        return (provider as? com.example.infrastructure.memory.semantic.EmbeddingQualityMarker)?.isSemantic ?: true
    }

    private fun generateLexicalVector(text: String): EmbeddingVector {
        val tokens = text.lowercase().split(Regex("[^\\w\\d]+")).filter { it.isNotBlank() }
        val vector = FloatArray(32) { 0.0f }
        for (token in tokens) {
            val hash = (token.hashCode() and 0x7FFFFFFF) % 32
            vector[hash] += 1.0f
        }
        val norm = sqrt(vector.sumOf { (it * it).toDouble() }).toFloat()
        if (norm > 0.001f) {
            for (i in vector.indices) vector[i] /= norm
        }
        return EmbeddingVector(vector)
    }

    private fun computeCosineSimilarity(vecA: FloatArray, vecB: FloatArray): Float {
        val len = minOf(vecA.size, vecB.size)
        if (len == 0) return 0.0f
        var dot = 0.0f
        var nA = 0.0f
        var nB = 0.0f
        for (i in 0 until len) {
            dot += vecA[i] * vecB[i]
            nA += vecA[i] * vecA[i]
            nB += vecB[i] * vecB[i]
        }
        val denom = (sqrt(nA.toDouble()) * sqrt(nB.toDouble())).toFloat()
        return if (denom > 1e-6f) (dot / denom).coerceIn(-1.0f, 1.0f) else 0.0f
    }
