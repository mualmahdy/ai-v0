    private fun ingestDocumentSync(doc: KnowledgeDocument) {
        val generatedChunks = splitIntoChunks(doc)
        val updatedDoc = doc.copy(totalChunks = generatedChunks.size)
        _documents.update { it + updatedDoc }
        chunks.addAll(generatedChunks)
        // P1-5: keep the retrieval index in sync with ingested chunks.
        generatedChunks.forEach { indexedChunks.add(indexChunk(it)) }
        // Audit 2026 (§29): bounded corpus — evict oldest when over the limits.
        enforceCorpusBounds()
    }

    /**
     * Ingests a new document into the knowledge base, splits into chunks, and
     * computes embeddings.
     *
     * Per Phase 4: the embedding adapter is resolved via the resource pipeline.
     * The first available ENABLED HEALTHY embedding ResourceRecord is used. If
     * none exists, the `fallbackEmbeddingProvider` (local in-process) is used.
     *
     * Per Section 8: each chunk records which embedding ResourceId generated
     * its vector. This preserves vector-compatibility boundaries across
     * different embedding resources.
     *
     * REPAIR ORDER §15: [projectId] scopes the ingested knowledge — null
     * (default) = WORKSPACE-SHARED, non-null = PROJECT-PRIVATE.
     */
    suspend fun ingestDocument(
        title: String,
        content: String,
        sourceUri: String,
        tags: List<String> = emptyList(),
        projectId: Long? = null
    ): KnowledgeDocument = withContext(Dispatchers.Default) {
        // Audit 2026: collision-free document id. A timestamp-only id made
        // two documents ingested within the same millisecond THE SAME
        // document (eviction/deletion then wiped them all at once).
        val docId = "doc_${System.currentTimeMillis()}_${docIdCounter.incrementAndGet()}"
        val doc = KnowledgeDocument(
            id = docId, title = title, sourceUri = sourceUri, content = content, tags = tags,
            projectId = projectId
        )
        val splitChunks = splitIntoChunks(doc)

        // Resolve the active embedding adapter via the resource pipeline.
        val (embeddingProvider, usedResourceId) = resolveEmbeddingProvider()
        activeEmbeddingResourceId = usedResourceId

        // P1-5 (audit 2026 §29 — ingestion embedding was NOT batched): ONE
        // batched embedding call for the whole document's chunks instead of
        // a provider round-trip per chunk (N provider calls → 1).
        val batchVectors: List<EmbeddingVector>? = if (embeddingProvider != null) {
            when (val batchOutcome = embeddingProvider.generateEmbeddings(splitChunks.map { it.text })) {
                is Outcome.Success -> batchOutcome.value
                else -> null
            }
        } else null

        val embeddedChunks = mutableListOf<DocumentChunk>()
        for ((index, chunk) in splitChunks.withIndex()) {
            var vector: EmbeddingVector? = batchVectors?.getOrNull(index)
            if (vector == null) {
                vector = generateLexicalVector(chunk.text)
            }
            // Provenance (audit 2026 fix): record WHICH embedding source produced
            // the vector so retrieval can enforce the compatibility boundary for
            // real (previously the boundary was claimed but never persisted).
            embeddedChunks.add(
                chunk.copy(
                    vector = vector,
                    metadata = chunk.metadata + mapOf(
                        "embeddingResourceId" to (usedResourceId?.value ?: "local_lexical"),
                        "embeddingSemantic" to isProviderSemantic(embeddingProvider).toString()
                    )
                )
            )
        }

        val completedDoc = doc.copy(totalChunks = embeddedChunks.size)
        _documents.update { it + completedDoc }
        chunks.addAll(embeddedChunks)
        // P1-5: keep the retrieval index in sync with ingested chunks.
        embeddedChunks.forEach { indexedChunks.add(indexChunk(it)) }
        rebuildDocProjectIndex()
        // Audit 2026 (§29): bounded corpus — evict oldest when over the limits.
        enforceCorpusBounds()

        // ------------------------------------------------------------
        // GAP-CLOSURE P1-14 (honest RAG persistence): a failed write is NO
        // LONGER swallowed with a fake "success" (RAM = ingested, DB =
        // missing → knowledge vanished after restart). The write is retried
        // once; on failure the returned document is marked
        // [KnowledgePersistenceState.FAILED] with a diagnostic so the UI and
        // callers know exactly what survived where.
        // ------------------------------------------------------------
        var persistenceState = KnowledgePersistenceState.PERSISTED
        var persistenceDiagnostic: String? = null
        if (persistenceService != null) {
            val targetWorkspace = currentWorkspaceId() ?: workspaceIdProvider()
            val persisted = runCatching {
                persistenceService.persistDocument(
                    workspaceId = targetWorkspace,
                    document = completedDoc,
                    chunks = embeddedChunks
                )
                true
            }
            if (persisted.getOrDefault(false)) {
                persistenceState = KnowledgePersistenceState.PERSISTED
            } else {
                // One honest retry before declaring failure.
                val retried = runCatching {
                    persistenceService.persistDocument(
                        workspaceId = targetWorkspace,
                        document = completedDoc,
                        chunks = embeddedChunks
                    )
                    true
                }
                if (retried.getOrDefault(false)) {
                    persistenceState = KnowledgePersistenceState.PERSISTED
                } else {
                    persistenceState = KnowledgePersistenceState.FAILED
                    persistenceDiagnostic = "RAG_PERSISTENCE_FAILED: أُدرج المستند في الفهرس الحي لكن تعذّر حفظه في قاعدة البيانات (فشلت محاولتان) — سيفقد المستند عند إعادة تشغيل التطبيق: ${persisted.exceptionOrNull()?.localizedMessage ?: retried.exceptionOrNull()?.localizedMessage ?: "سبب غير معروف"}"
                }
            }
        } else {
            persistenceState = KnowledgePersistenceState.PENDING
            persistenceDiagnostic = "لا يوجد مخزن دائم مهيأ — المستند في الذاكرة فقط."
        }

        completedDoc.copy(
            persistenceState = persistenceState,
            persistenceDiagnostic = persistenceDiagnostic
        )
    }

    /**
     * Resolve the active embedding adapter via the resource pipeline.
     *
     * Returns (adapter, resourceId) where:
     *   - adapter: the resolved `EmbeddingProviderPort` (or null if none available)
     *   - resourceId: the `ResourceId` of the resolved adapter (or null for fallback)
     *
     * Per Phase 4: no silent fallback to a hardcoded default. If no embedding
     * ResourceRecord is registered, the `fallbackEmbeddingProvider` is used
     * (which is the local in-process adapter explicitly injected by
     * `AppContainer`). The fallback path is HONEST — the `RetrievalMode` is
     * `LEXICAL_FALLBACK`, not `HYBRID`.
     */
    private suspend fun resolveEmbeddingProvider(): Pair<EmbeddingProviderPort?, ResourceId?> {
        // Find the first ENABLED HEALTHY embedding ResourceRecord.
        val embeddingResources = resourceRegistry.listResources()
            .filter { it.resourceType == ResourceType.EMBEDDING
                && (it.lifecycleState == com.example.domain.core.resource.ResourceLifecycleState.ENABLED
                    || it.lifecycleState == com.example.domain.core.resource.ResourceLifecycleState.ACTIVE)
                && it.runtimeSupported
                && it.healthStatus != HealthStatus.UNAVAILABLE
            }
        // Prefer the one with HEALTHY health status.
        val chosen = embeddingResources.firstOrNull { it.healthStatus == HealthStatus.HEALTHY }
            ?: embeddingResources.firstOrNull()
        if (chosen != null) {
            val resolution = runtimeAdapterResolver.resolveEmbeddingAdapter(chosen.resourceId)
            val adapter = when (resolution) {
                is Outcome.Success -> resolution.value
                is Outcome.Degraded -> resolution.partialValue
                is Outcome.Error -> null
            }
            if (adapter != null) return adapter to chosen.resourceId
        }
        // Fallback to the injected local adapter. This is HONEST — the
        // `RetrievalMode` will be LEXICAL_FALLBACK, not HYBRID.
        return fallbackEmbeddingProvider to null
    }

    private fun splitIntoChunks(doc: KnowledgeDocument, chunkSize: Int = 300, overlap: Int = 50): List<DocumentChunk> {
        val text = doc.content
        val chunkList = mutableListOf<DocumentChunk>()
        var start = 0
        var chunkIndex = 0
        while (start < text.length) {
            val end = (start + chunkSize).coerceAtMost(text.length)
            val chunkText = text.substring(start, end).trim()
            if (chunkText.isNotBlank()) {
                chunkList.add(
                    DocumentChunk(
                        id = "${doc.id}_c$chunkIndex",
                        documentId = doc.id,
                        documentTitle = doc.title,
                        chunkIndex = chunkIndex,
                        text = chunkText,
                        tokenCount = chunkText.length / 4
                    )
                )
                chunkIndex++
            }
            if (end == text.length) break
            start += (chunkSize - overlap).coerceAtLeast(1)
        }
        return chunkList
    }

