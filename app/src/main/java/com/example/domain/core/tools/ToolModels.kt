package com.example.domain.core.tools

import com.example.domain.core.capability.CapabilityType
import com.example.domain.core.capability.Locality
import com.example.domain.core.capability.NetworkRequirement
import com.example.domain.core.capability.SideEffectClassification

/**
 * Definition of a parameter accepted by a tool.
 */
data class ToolParameter(
    val name: String,
    val type: String, // "string", "number", "boolean", "object", "array"
    val description: String,
    val isRequired: Boolean = true,
    val enumValues: List<String> = emptyList()
)

/**
 * Metadata, schema declaration, and structured capability descriptors of a callable tool.
 */
data class ToolDeclaration(
    val name: String,
    val description: String,
    val parameters: List<ToolParameter> = emptyList(),
    val isSensitive: Boolean = false,
    val requiresHumanConsent: Boolean = false,
    val providedCapabilities: Set<CapabilityType> = setOf(CapabilityType.TOOL_EXECUTION),
    val networkRequirement: NetworkRequirement = NetworkRequirement.LOCAL_ONLY,
    val sideEffects: SideEffectClassification = SideEffectClassification.READ_ONLY,
    val requiredPermissions: List<String> = emptyList(),
    val locality: Locality = Locality.LOCAL_ON_DEVICE
)


/**
 * Input payload sent to a tool for execution.
 */
data class ToolInput(
    val toolName: String,
    val arguments: Map<String, Any?>,
    val executionId: String? = null,
    val contextAttributes: Map<String, String> = emptyMap()
)

/**
 * Output generated by a tool upon execution.
 */
data class ToolOutput(
    val content: String,
    val isTruncated: Boolean = false,
    val rawBytesCount: Long = 0L,
    val attributes: Map<String, String> = emptyMap()
)

/**
 * Categorized domain failures for tool execution.
 */
sealed interface ToolFailure {
    data class InvalidParameters(val missingOrInvalidKeys: List<String>, val reason: String) : ToolFailure
    data class PermissionDenied(val pathOrResource: String, val message: String) : ToolFailure
    data class ExecutionTimeout(val timeoutMs: Long) : ToolFailure
    data class SecurityDenied(val ruleName: String, val message: String) : ToolFailure
    data class CapabilityUnavailable(val capabilityName: String, val message: String) : ToolFailure
    data class InternalExecutionError(val message: String, val exitCode: Int? = null) : ToolFailure
}
